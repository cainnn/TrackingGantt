export const WEEKLY_SUMMARY_OUTPUT_REQUIREMENT =
  '周报最终回答必须只输出一句完整中文句子，固定结构为“{完工日期结论}，本周主要完成工作：{完成事项}，工期变化：{工期说明}，主要风险：{风险说明}。”；完工日期结论只能是“完工日期不变”“完工日期推迟到YYYY-MM-DD”或“完工日期提前到YYYY-MM-DD”；完成事项只写本周已完成的1至3项具体工作并使用任务名称，不得在这里写工期变化、延期原因、下游影响、未完成工作或风险，若没有可靠数据可确认完成事项则写“暂无可确认的完成工作”，不得猜测；工期说明单独写任务延期或提前的原因、级联影响和项目整体工期变化，若计划无变化则写“本周计划不变，工期不变”；风险说明单独写尚未完成工作及后续风险，若无明显风险则写“暂无明显风险”；控制在180个汉字以内，不要标题、列表、表格、Markdown或换行，除三个固定字段名后的冒号外，句内仅用逗号或分号连接并只在句末使用一个句号。'

export function isWeeklySummaryIntent(text: string): boolean {
  return /周报|本周|这周|上周|周总结|weekly|this week|last week/i.test(text)
}
